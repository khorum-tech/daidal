/**
 * Write wrangler.prod.jsonc: wrangler.jsonc with prod's own D1 database id and Access AUD filled in. wrangler.jsonc
 * keeps only placeholders (it works for `wrangler dev` and the tests, which need neither), so nothing
 * account-specific sits in the repository; CI fills them from the `production` environment.
 *
 *   PROD_D1_ID=… PROD_ACCESS_AUD=… node scripts/prod-config.mjs
 *
 * The pure parts are exported so the Worker tests can check them; only the command at the bottom touches files.
 */
import { KNOWN_KEYS, parseJsonc } from "./stage-config.mjs";

/** What wrangler.jsonc holds in place of the real values. */
export const PLACEHOLDER_D1_ID = "00000000-0000-0000-0000-000000000000";

/** The prod config built from wrangler.jsonc. Throws when a value is missing or still the placeholder. */
export function prodConfig(base, env) {
  const missing = ["PROD_D1_ID", "PROD_ACCESS_AUD"].filter(name => !String(env[name] ?? "").trim());
  if (missing.length) throw new Error(`prod-config: set ${missing.join(" and ")} (the production environment's secrets or variables; see docs/stage.md)`);
  const unknown = Object.keys(base).filter(key => !KNOWN_KEYS.has(key));
  if (unknown.length) {
    const names = unknown.map(k => JSON.stringify(k)).join(", ");
    throw new Error(`prod-config: wrangler.jsonc has ${names}, which the config scripts do not know`);
  }
  const databases = Array.isArray(base.d1_databases) ? base.d1_databases : [];
  if (databases.length !== 1) throw new Error("prod-config: expected exactly one D1 database in wrangler.jsonc");
  const d1Id = env.PROD_D1_ID.trim();
  if (d1Id === PLACEHOLDER_D1_ID) throw new Error("prod-config: PROD_D1_ID is the placeholder; set prod's real database id");
  return {
    ...base,
    d1_databases: [{ ...databases[0], database_id: d1Id }],
    vars: { ...base.vars, ACCESS_AUD: env.PROD_ACCESS_AUD.trim() },
  };
}

export function prodConfigText(baseText, env) {
  return `// Generated by scripts/prod-config.mjs from wrangler.jsonc. Do not edit or commit.\n${JSON.stringify(prodConfig(parseJsonc(baseText), env), null, 2)}\n`;
}

const invokedDirectly = typeof process !== "undefined" && process.argv?.[1] && import.meta.url === (await import("node:url")).pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  const { readFileSync, writeFileSync } = await import("node:fs");
  try {
    writeFileSync("wrangler.prod.jsonc", prodConfigText(readFileSync("wrangler.jsonc", "utf8"), process.env));
    console.log("wrote wrangler.prod.jsonc");
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  }
}
