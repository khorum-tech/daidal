import { describe, expect, it } from "vitest";
import { PLACEHOLDER_D1_ID, prodConfig, prodConfigText, prodSecrets } from "../../scripts/prod-config.mjs";
import { parseJsonc } from "../../scripts/stage-config.mjs";
import wranglerText from "../../wrangler.jsonc?raw";

const BASE = {
  name: "skope",
  routes: [{ pattern: "skope.khorum-oss.org", custom_domain: true }],
  d1_databases: [{ binding: "DB", database_name: "skope", database_id: PLACEHOLDER_D1_ID, migrations_dir: "migrations" }],
  vars: { ACCESS_TEAM_DOMAIN: "https://khorum.cloudflareaccess.com", ACCESS_AUD: "" },
};

describe("prod-config", () => {
  it("fills prod's database id and AUD into the config, leaving everything else as it is", () => {
    const config = prodConfig(BASE, { PROD_D1_ID: " real-db-id ", PROD_ACCESS_AUD: "real-aud" });
    expect(config.d1_databases).toEqual([{ ...BASE.d1_databases[0], database_id: "real-db-id" }]);
    // The AUD is not a variable (wrangler prints those in the deploy log): it goes up as a secret.
    expect(config.vars).toEqual({ ACCESS_TEAM_DOMAIN: "https://khorum.cloudflareaccess.com" });
    expect(prodSecrets({ PROD_ACCESS_AUD: " real-aud " })).toEqual({ ACCESS_AUD: "real-aud" });
    expect(config.routes).toEqual(BASE.routes);
    expect(prodConfigText(JSON.stringify(BASE), { PROD_D1_ID: "x", PROD_ACCESS_AUD: "y" })).toMatch(/^\/\/ Generated by scripts\/prod-config\.mjs/);
  });

  it("refuses to run without both values, or with the placeholder id", () => {
    expect(() => prodConfig(BASE, {})).toThrow(/PROD_D1_ID and PROD_ACCESS_AUD/);
    expect(() => prodConfig(BASE, { PROD_D1_ID: "x" })).toThrow(/PROD_ACCESS_AUD/);
    expect(() => prodConfig(BASE, { PROD_D1_ID: PLACEHOLDER_D1_ID, PROD_ACCESS_AUD: "y" })).toThrow(/placeholder/);
    expect(() => prodConfig({ ...BASE, kv_namespaces: [] }, { PROD_D1_ID: "x", PROD_ACCESS_AUD: "y" })).toThrow(/kv_namespaces/);
  });

  it("matches the repository's wrangler.jsonc, which keeps only placeholders", () => {
    const repo = parseJsonc(wranglerText);
    expect(repo.d1_databases[0].database_id).toBe(PLACEHOLDER_D1_ID);
    expect(repo.vars.ACCESS_AUD).toBe("");
    // Prod answers on its main hostname first and keeps the old one: dropping a name here detaches it on deploy.
    expect(repo.routes).toEqual([
      { pattern: "daidal.khorum.org", custom_domain: true },
      { pattern: "skope.khorum-oss.org", custom_domain: true },
    ]);
    expect(prodConfig(repo, { PROD_D1_ID: "x", PROD_ACCESS_AUD: "y" }).d1_databases[0].database_id).toBe("x");
  });
});
